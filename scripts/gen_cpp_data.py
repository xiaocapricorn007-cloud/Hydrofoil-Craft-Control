"""Export the validated Python model's tables/constants and a set of golden
force evaluations to C++ headers, so libfoil can be checked against plant.py.

  python scripts/gen_cpp_data.py
writes ros_ws/src/hydrofoil_physics/include/hydrofoil/generated_data.hpp
       ros_ws/src/hydrofoil_physics/test/golden.hpp
"""
import sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import numpy as np
from hydrofoil.params import Params, Physics
from hydrofoil.plant import Hydrofoil, Env, Unsteady, NX
from hydrofoil.linearize import trim
from hydrofoil.waves import regular, calm, SeaState

P = Params()
OUT = ROOT / "ros_ws/src/hydrofoil_physics"


def arr(name, a):
    body = ", ".join(f"{v:.17g}" for v in np.asarray(a, float).ravel())
    return f"inline constexpr std::array<double, {np.size(a)}> {name} = {{{body}}};\n"


h = ["// GENERATED by scripts/gen_cpp_data.py from hydrofoil/params.py -- do not edit.\n",
     "#pragma once\n#include <array>\nnamespace hf::data {\n"]
pol = P.polar
h += [arr("POLAR_ALPHA_DEG", pol["alpha"]), arr("POLAR_CL", pol["cl"]), arr("POLAR_CDV", pol["cdv"]),
      arr("POLAR_CDI", pol["cdi"]), arr("POLAR_CM", pol["cm"]),
      arr("KT_POLY", P.KT_poly), arr("KQ_POLY", P.KQ_poly)]
for k, v in dict(CD_STRUT0=P.cd_strut0, ROLL_INT_FS=P.L_FS, ROLL_INT_FP=P.L_FP, ROLL_INT_A=P.L_A).items():
    h.append(f"inline constexpr double {k} = {v:.17g};\n")
wk = Hydrofoil(Params()).wake          # fore-foil wake upwash table (phase 4)
h += [arr("WAKE_H", wk.h), arr("WAKE_G", wk.G)]
h.append("}  // namespace hf::data\n")
(OUT / "include/hydrofoil/generated_data.hpp").write_text("".join(h), newline="\n")

# ---------------------------------------------------------------- golden set
m = Hydrofoil(wagner=False)
core0, d0, rpm0 = trim(m, 7.0)
rng = np.random.default_rng(1)
cases = []
waves = [calm(), regular(0.1, 3.0, np.pi, 0.4), regular(0.2, 1.8, 0.0, 1.1)]
wave_defs = [(0, 0, 0, 0), (0.1, 3.0, np.pi, 0.4), (0.2, 1.8, 0.0, 1.1)]
for i in range(90):
    c = core0.copy()
    if i > 0:
        c[0] = rng.uniform(0, 50)                   # xN
        c[1] += rng.uniform(-0.2, 0.2)              # z
        c[2] = rng.uniform(-0.12, 0.12)             # phi
        c[3] = rng.uniform(-0.08, 0.08)             # theta
        c[4] = rng.uniform(5, 14)                   # u
        c[5] = rng.uniform(-0.6, 0.6)               # w
        c[6] = rng.uniform(-0.4, 0.4)               # p
        c[7] = rng.uniform(-0.3, 0.3)               # q
    d = d0 + (rng.uniform(-0.1, 0.1, 3) if i > 0 else 0)
    rpm = rpm0 + (rng.uniform(-400, 1200) if i > 0 else 0)
    wi = i % 3
    t = rng.uniform(0, 20)
    # environment: first 60 cases = reference model (no env), last 30 = phase 3 env
    if i < 60:
        env = Env()
        envrow = [-1.0, 0, 0, 0, 0, 0]
    else:
        env = Env(rho=rng.uniform(995, 1030), current=tuple(rng.uniform(-1.5, 1.5, 2)),
                  wind=tuple(rng.uniform(-15, 15, 2)), aero=True)
        envrow = [env.rho, *env.current, *env.wind, 1]
    m.env = env
    tau, alphas = m.forces(c, lambda j, a: a, d, rpm, t, waves[wi])
    # remove gravity: libfoil returns hydrodynamic + propeller (+ air) wrench only
    tau = tau.copy()
    tau[0] -= -P.mass * P.g * np.sin(c[3])
    tau[1] -= P.mass * P.g * np.cos(c[3]) * np.cos(c[2])
    cases.append(np.r_[c, d, rpm, t, wave_defs[wi], tau, alphas, envrow])
cases = np.array(cases)

# blended sea: field A from t=0 (ramp 5 s), replaced by field B at t=10 (ramp 4 s)
sea = SeaState()
sea.set(waves[1], 0.0, 5.0)
sea.set(waves[2], 10.0, 4.0)
blend = []
for t in (1.0, 4.9, 9.0, 10.5, 12.0, 13.9, 14.5, 25.0):
    z, v = sea.at(3.0, 1.0, 0.4, t)
    blend.append([t, z, *v])
blend = np.array(blend)

g = ["// GENERATED by scripts/gen_cpp_data.py from hydrofoil/plant.py -- do not edit.\n",
     "// columns: xN z phi theta u w p q | dFS dFP dA | rpm | t | wave amp omega psi phase |"
     " X Z K M (no gravity) | alphaFS alphaFP alphaA | rho cur_n cur_e wind_n wind_e aero\n",
     "#pragma once\n#include <array>\nnamespace hf::golden {\n",
     f"inline constexpr int N = {len(cases)};\ninline constexpr int COLS = {cases.shape[1]};\n",
     f"inline constexpr double TRIM_DF = {d0[0]:.17g};\ninline constexpr double TRIM_DA = {d0[2]:.17g};\n",
     f"inline constexpr double TRIM_RPM = {rpm0:.17g};\n",
     f"inline constexpr double CASES[{len(cases)}][{cases.shape[1]}] = {{\n"]
for r in cases:
    g.append("  {" + ", ".join(f"{v:.17g}" for v in r) + "},\n")
g.append("};\n")
g.append("// blended sea at (xN=3, yE=1, depth=0.4): t, zeta, u, v, w\n")
g.append(f"inline constexpr int NB = {len(blend)};\ninline constexpr double BLEND[{len(blend)}][5] = {{\n")
for r in blend:
    g.append("  {" + ", ".join(f"{v:.17g}" for v in r) + "},\n")
g.append("};\n")

# ---------------------------------------------------------------- phase 4
# derivative cases at random filter states: each switch alone, all, none, mixes
masks = [1, 2, 4, 8, 16, 32, 64, 127, 0, 127, 36, 21]
models = {}
p4 = []
for i in range(144):
    mask = masks[i % len(masks)]
    if mask not in models:
        ph = Physics(*[bool(mask >> b & 1) for b in range(7)])
        models[mask] = Hydrofoil(Params(phys=ph), wagner=True)
    mm = models[mask]
    c = core0.copy()
    c[0] = rng.uniform(0, 50); c[1] = rng.uniform(-0.72, -0.1); c[2] = rng.uniform(-0.12, 0.12)
    c[3] = rng.uniform(-0.08, 0.08); c[4] = rng.uniform(5, 14); c[5] = rng.uniform(-0.6, 0.6)
    c[6] = rng.uniform(-0.4, 0.4); c[7] = rng.uniform(-0.3, 0.3)
    act = d0 + rng.uniform(-0.08, 0.08, 3)
    wag = np.column_stack([0.165 * act, 0.335 * act]) + rng.uniform(-0.02, 0.02, (3, 2))
    kus = rng.uniform(-0.03, 0.03, (3, 2))
    vent = rng.uniform(0, 1, 3)
    gam = rng.uniform(0, 0.3, 2)
    cmd = act + rng.uniform(-0.2, 0.2, 3)
    rpm = rpm0 + rng.uniform(-400, 1200)
    t = rng.uniform(0, 20)
    wi = i % 3
    if i % 2:
        env = Env(rho=rng.uniform(995, 1030), current=tuple(rng.uniform(-1.5, 1.5, 2)),
                  wind=tuple(rng.uniform(-15, 15, 2)), aero=True)
        envrow = [env.rho, *env.current, *env.wind, 1]
    else:
        env, envrow = Env(), [-1.0, 0, 0, 0, 0, 0]
    mm.env = env
    x = np.zeros(NX); x[:8] = c; x[8:11] = act
    x[11:17] = wag.ravel(); x[17:23] = kus.ravel(); x[23:26] = vent; x[26:28] = gam
    dx = mm.deriv(x, cmd, rpm, t, waves[wi])
    tau, _ = mm.forces(c, None, act, rpm, t, waves[wi], ust=Unsteady(wag, kus, vent, gam))
    tau = tau.copy()
    tau[0] -= -P.mass * P.g * np.sin(c[3])
    tau[1] -= P.mass * P.g * np.cos(c[3]) * np.cos(c[2])
    if mm.P.phys.added_mass:
        for j, (nm, r, S, cs, Ld) in enumerate(mm.foils):
            Fz = -mm.P.A33[j] * mm._last["V"][j] * dx[8 + j]
            tau += np.array([0.0, Fz, r[1] * Fz, -r[0] * Fz])
    p4.append(np.r_[c, act, x[11:28], cmd, rpm, t, wave_defs[wi], envrow, mask, tau, dx[5:8], dx[8:28]])
p4 = np.array(p4)
g.append("// phase 4 derivative cases.  columns: core(8) | act(3) | wag(6) kus(6) vent(3) gam(2) |\n"
         "// cmd(3) | rpm | t | wave(4) | env(6) | physics mask | X Z K M (no gravity, with the\n"
         "// added-mass reaction) | w' p' q' | dact(3) | d wag(6) d kus(6) d vent(3) d gam(2)\n")
g.append(f"inline constexpr int N4 = {len(p4)};\ninline constexpr int COLS4 = {p4.shape[1]};\n")
g.append(f"inline constexpr double CASES4[{len(p4)}][{p4.shape[1]}] = {{\n")
for r in p4:
    g.append("  {" + ", ".join(f"{v:.17g}" for v in r) + "},\n")
g.append("};\n")
# trims: mask, U, dF, dA, rpm; CG 0.3 m above the water
tr = []
for mask in (0, 32, 127):
    ph = Physics(*[bool(mask >> b & 1) for b in range(7)])
    for U in (7.0, 10.0):
        cc, dd, rr = trim(Hydrofoil(Params(phys=ph), wagner=False), U, -0.3)
        tr.append([mask, U, dd[0], dd[2], rr])
g.append(f"inline constexpr int NT = {len(tr)};\ninline constexpr double TRIMS[{len(tr)}][5] = {{\n")
for r in tr:
    g.append("  {" + ", ".join(f"{v:.17g}" for v in r) + "},\n")
g.append("};\n")
g.append("inline constexpr double MA[9] = {" + ", ".join(f"{v:.17g}" for v in P.MA.ravel()) + "};\n")
g.append("inline constexpr double A33[3] = {" + ", ".join(f"{v:.17g}" for v in P.A33) + "};\n")
g.append("}  // namespace hf::golden\n")
(OUT / "test/golden.hpp").write_text("".join(g), newline="\n")
print("wrote generated_data.hpp and golden.hpp;", len(cases), "force cases,", len(blend), "blend cases,",
      len(p4), "phase-4 derivative cases,", len(tr), "trims")
