"""Generate the craft's visual meshes (OBJ) and textures (PNG) procedurally.

    python scripts/make_craft_visuals.py

Writes ros_ws/src/hydrofoil_physics/models/hydrofoil_craft/{meshes,materials/textures}.
Everything is in the link frame (FLU: x forward, y left/port, z up, origin =
CG), so the visuals in model.sdf need no pose.

Fixed by the reference (thesis Table A.1): foil and strut positions, foil span,
area and chord, strut chords, propeller diameter.  ILLUSTRATIVE (the reference
gives no above-water geometry): hull lines, deck, solar array layout, pilot.
The hull bottom is kept above z = 0, i.e. at least 0.3 m above the water at the
design ride height; the physics has no hull, so the visuals must not suggest one
that would touch the water in normal flight.
"""
import math
import pathlib
import struct
import zlib

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
MODEL = ROOT / "ros_ws/src/hydrofoil_physics/models/hydrofoil_craft"
MESH = MODEL / "meshes"
TEX = MODEL / "materials/textures"


# ------------------------------------------------------------------ mesh kit
class Mesh:
    def __init__(self):
        self.v, self.vt, self.f = [], [], []      # f: list of (i, j, k) with uv indices or None

    def tri(self, a, b, c, uv=None, outward=None):
        a, b, c = (np.asarray(p, float) for p in (a, b, c))
        n = np.cross(b - a, c - a)
        if outward is not None and np.dot(n, outward(((a + b + c) / 3))) < 0:
            b, c = c, b
            if uv is not None:
                uv = (uv[0], uv[2], uv[1])
        base = len(self.v)
        self.v += [a, b, c]
        if uv is not None:
            tb = len(self.vt)
            self.vt += list(uv)
            self.f.append(((base, tb), (base + 1, tb + 1), (base + 2, tb + 2)))
        else:
            self.f.append(((base, None), (base + 1, None), (base + 2, None)))

    def quad(self, a, b, c, d, uv=None, outward=None):
        self.tri(a, b, c, None if uv is None else (uv[0], uv[1], uv[2]), outward)
        self.tri(a, c, d, None if uv is None else (uv[0], uv[2], uv[3]), outward)

    def grid(self, P, outward=None, uv=None):
        """P: (nu, nv, 3) surface samples -> quads."""
        nu, nv = P.shape[:2]
        for i in range(nu - 1):
            for j in range(nv - 1):
                q = (P[i, j], P[i + 1, j], P[i + 1, j + 1], P[i, j + 1])
                t = None if uv is None else (uv[i, j], uv[i + 1, j], uv[i + 1, j + 1], uv[i, j + 1])
                self.quad(*q, uv=t, outward=outward)

    def write(self, path, smooth_angle=35.0):
        """OBJ with smoothed vertex normals (faces meeting at a sharper angle stay creased)."""
        V = np.array(self.v)
        F = [[i for i, _ in f] for f in self.f]
        fn = []
        for a, b, c in F:
            n = np.cross(V[b] - V[a], V[c] - V[a])
            ln = np.linalg.norm(n)
            fn.append(n / ln if ln > 1e-12 else np.array([0, 0, 1.0]))
        fn = np.array(fn)
        # group coincident positions
        key = {}
        for idx, p in enumerate(V):
            key.setdefault(tuple(np.round(p, 6)), []).append(idx)
        owner = {}
        for fi, f in enumerate(F):
            for i in f:
                owner[i] = fi
        cos_lim = math.cos(math.radians(smooth_angle))
        N = np.zeros_like(V)
        for idxs in key.values():
            for i in idxs:
                ni = fn[owner[i]]
                acc = np.zeros(3)
                for j in idxs:
                    nj = fn[owner[j]]
                    if np.dot(ni, nj) >= cos_lim:
                        acc += nj
                N[i] = acc / max(np.linalg.norm(acc), 1e-12)
        with open(path, "w", newline="\n") as fh:
            fh.write("# generated by scripts/make_craft_visuals.py\n")
            for p in V:
                fh.write(f"v {p[0]:.5f} {p[1]:.5f} {p[2]:.5f}\n")
            for n in N:
                fh.write(f"vn {n[0]:.4f} {n[1]:.4f} {n[2]:.4f}\n")
            for t in self.vt:
                fh.write(f"vt {t[0]:.5f} {t[1]:.5f}\n")
            for f in self.f:
                if f[0][1] is None:
                    fh.write("f " + " ".join(f"{i + 1}//{i + 1}" for i, _ in f) + "\n")
                else:
                    fh.write("f " + " ".join(f"{i + 1}/{t + 1}/{i + 1}" for i, t in f) + "\n")
        return len(self.f)


def away_from(axis_point_fn):
    return lambda c: c - axis_point_fn(c)


def cylinder(m, p0, p1, r0, r1=None, n=16, caps=True):
    r1 = r0 if r1 is None else r1
    p0, p1 = np.asarray(p0, float), np.asarray(p1, float)
    ax = p1 - p0
    ax /= np.linalg.norm(ax)
    u = np.cross(ax, [0, 0, 1.0])
    if np.linalg.norm(u) < 1e-6:
        u = np.cross(ax, [0, 1.0, 0])
    u /= np.linalg.norm(u)
    w = np.cross(ax, u)
    ring = lambda c, r: [c + r * (math.cos(t) * u + math.sin(t) * w) for t in np.linspace(0, 2 * np.pi, n + 1)]
    A, B = ring(p0, r0), ring(p1, r1)
    mid = (p0 + p1) / 2
    for i in range(n):
        m.quad(A[i], A[i + 1], B[i + 1], B[i], outward=lambda c: c - (p0 + np.dot(c - p0, ax) * ax))
    if caps:
        for i in range(n):
            m.tri(p0, A[i + 1], A[i], outward=lambda c: -ax)
            m.tri(p1, B[i], B[i + 1], outward=lambda c: ax)


def ellipsoid(m, c, r, n=16, k=10):
    c, r = np.asarray(c, float), np.asarray(r, float)
    th = np.linspace(0, np.pi, k + 1)
    ph = np.linspace(0, 2 * np.pi, n + 1)
    P = np.array([[c + r * [math.sin(t) * math.cos(p), math.sin(t) * math.sin(p), math.cos(t)] for p in ph] for t in th])
    m.grid(P, outward=lambda q: q - c)


def box(m, lo, hi, uv_top=False):
    lo, hi = np.asarray(lo, float), np.asarray(hi, float)
    c = (lo + hi) / 2
    x0, y0, z0 = lo
    x1, y1, z1 = hi
    P = lambda x, y, z: np.array([x, y, z])
    out = lambda q: q - c
    m.quad(P(x0, y0, z0), P(x1, y0, z0), P(x1, y1, z0), P(x0, y1, z0), outward=out)
    top_uv = ((0, 0), (1, 0), (1, 1), (0, 1)) if uv_top else None
    m.quad(P(x0, y0, z1), P(x1, y0, z1), P(x1, y1, z1), P(x0, y1, z1), uv=top_uv, outward=out)
    for (a, b) in (((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x1, y1), (x0, y1)), ((x0, y1), (x0, y0))):
        m.quad(P(*a, z0), P(*b, z0), P(*b, z1), P(*a, z1), outward=out)


# ------------------------------------------------------------------ hull
XT, XB, XM = -3.1, 2.5, -0.4         # transom, bow tip, max beam station
BMAX = 0.75


def half_beam(x):
    if x >= XM:
        return BMAX * math.sqrt(max(0.0, 1 - ((x - XM) / (XB - XM)) ** 2)) ** 0.85
    return BMAX - 0.12 * ((XM - x) / (XM - XT)) ** 2


def keel_z(x):
    return 0.03 + (0.26 * ((x - 1.0) / (XB - 1.0)) ** 2 if x > 1.0 else 0.0)


def sheer_z(x):
    return 0.36 + 0.07 * max(0.0, (x - 0.8) / (XB - 0.8)) ** 1.5


def hull_meshes():
    xs = np.r_[np.linspace(XT, 1.6, 22), np.linspace(1.62, XB - 0.002, 16)]
    nb, ns = 5, 6                      # points across bottom (keel->chine) and side (chine->sheer)
    bot, side_w, side_b, deck = Mesh(), Mesh(), Mesh(), Mesh()
    axis = lambda c: np.array([c[0], 0.0, 0.22])
    for sgn in (+1, -1):
        B, Sw, Sb, D = [], [], [], []
        for x in xs:
            b, zk, zs = half_beam(x), keel_z(x), sheer_z(x)
            yc, zc = 0.82 * b, zk + 0.11 * min(1.0, b / 0.3)
            B.append([[x, sgn * yc * t, zk + (zc - zk) * t ** 1.3] for t in np.linspace(0, 1, nb)])
            col = []
            for t in np.linspace(0, 1, ns):
                y = yc + (b - yc) * math.sin(t * math.pi / 2)        # flared topside
                col.append([x, sgn * y, zc + (zs - zc) * t])
            Sw.append(col[:-2])
            Sb.append(col[-3:])                                      # navy sheer stripe
            D.append([[x, sgn * b * t, zs + 0.02 * (1 - t * t)] for t in np.linspace(0, 1, 6)])
        bot.grid(np.array(B), outward=away_from(axis))
        side_w.grid(np.array(Sw), outward=away_from(axis))
        side_b.grid(np.array(Sb), outward=away_from(axis))
        deck.grid(np.array(D), outward=lambda c: np.array([0, 0, 1.0]))
    # transom (flat plate at XT)
    x = XT
    b, zk, zs = half_beam(x), keel_z(x), sheer_z(x)
    yc, zc = 0.82 * b, zk + 0.11
    poly = [(0, zk), (yc, zc), (b, zs), (0, zs + 0.02), (-b, zs), (-yc, zc)]
    tr = Mesh()
    cy = (zk + zs) / 2
    for i in range(len(poly)):
        a, c2 = poly[i], poly[(i + 1) % len(poly)]
        tr.tri([x, 0, cy], [x, a[0], a[1]], [x, c2[0], c2[1]], outward=lambda c: np.array([-1.0, 0, 0]))
    return dict(hull_bottom=bot, hull_side=side_w, hull_stripe=side_b, deck=deck, transom=tr)


# ------------------------------------------------------------------ solar array
PANEL_X0, PANEL_X1, PANEL_Y = -2.8, 1.05, 0.62
PANEL_Z = 0.42


def solar_meshes():
    cells, frame = Mesh(), Mesh()
    nx, ny = 4, 2
    L, W = (PANEL_X1 - PANEL_X0) / nx, 2 * PANEL_Y / ny
    for i in range(nx):
        for j in range(ny):
            x0, y0 = PANEL_X0 + i * L + 0.015, -PANEL_Y + j * W + 0.015
            x1, y1 = x0 + L - 0.03, y0 + W - 0.03
            # textured top face
            z = PANEL_Z + 0.025
            cells.quad([x0, y0, z], [x1, y0, z], [x1, y1, z], [x0, y1, z],
                       uv=((0, 0), (1, 0), (1, 1), (0, 1)), outward=lambda c: np.array([0, 0, 1.0]))
            # aluminium frame rim + body
            box(frame, [x0 - 0.012, y0 - 0.012, PANEL_Z], [x1 + 0.012, y1 + 0.012, PANEL_Z + 0.024])
    # stand-offs to the deck
    for x in np.linspace(PANEL_X0 + 0.2, PANEL_X1 - 0.2, 5):
        for y in (-0.45, 0.0, 0.45):
            cylinder(frame, [x, y, sheer_z(x) - 0.01], [x, y, PANEL_Z], 0.018, n=8)
    return dict(solar_cells=cells, solar_frame=frame)


# ------------------------------------------------------------------ foils, struts, pod
FOILS = [  # FLU arms (thesis Table A.1, y and z flipped), strut chord
    ("fs", (1.1, -0.62, -0.75), 0.08),
    ("fp", (1.1, 0.62, -0.75), 0.08),
    ("a", (-2.45, 0.0, -0.96), 0.10),
]
SPAN, AREA_F, AREA_A = 0.76, 0.048, 0.046


def naca(t, camber=0.0, n=14):
    """Closed NACA 4-digit-like section, x/c in [0, 1] from LE; returns (x, z) loop."""
    beta = np.linspace(0, np.pi, n)
    xc = (1 - np.cos(beta)) / 2
    yt = 5 * t * (0.2969 * np.sqrt(xc) - 0.1260 * xc - 0.3516 * xc ** 2 + 0.2843 * xc ** 3 - 0.1036 * xc ** 4)
    p = 0.4
    yc = np.where(xc < p, camber / p ** 2 * (2 * p * xc - xc ** 2), camber / (1 - p) ** 2 * ((1 - 2 * p) + 2 * p * xc - xc ** 2))
    up = np.column_stack([xc, yc + yt])
    lo = np.column_stack([xc, yc - yt])[::-1]
    return np.vstack([up, lo[1:]])


def strut_and_foil_meshes():
    strut, foil, pod, prop = Mesh(), Mesh(), Mesh(), Mesh()
    for name, (x, y, z), cs in FOILS:
        # strut: NACA 0012 extruded from the foil up into the hull
        sec = naca(0.12)
        ztop = keel_z(x) + 0.12 if name != "a" else keel_z(x) + 0.05
        P = []
        for zz in (z, ztop):
            P.append([[x + cs * 0.25 - cs * s[0], y + cs * s[1], zz] for s in sec])
        P = np.array(P)
        strut.grid(P, outward=lambda c, x=x, y=y, cs=cs: np.array([0, c[1] - y, 0]) + 1e-3 * np.array([c[0] - x, 0, 0]))
        # foil: elliptic planform, NACA x412-like section (4 % thick-to-chord 12 %, camber 2 %)
        S = AREA_F if name != "a" else AREA_A
        c0 = 4 * S / (math.pi * SPAN)
        sec = naca(0.12, camber=0.02)
        ys = SPAN / 2 * np.cos(np.linspace(np.pi, 0, 15))
        rows = []
        for yy in ys:
            c = max(0.012, c0 * math.sqrt(max(0.0, 1 - (2 * yy / SPAN) ** 2)))
            rows.append([[x + 0.25 * c0 - (0.25 * c0 - 0.25 * c) - c * s[0] + 0.25 * c - 0.25 * c, y + yy, z + c * s[1]] for s in sec])
        F = np.array(rows)
        foil.grid(F, outward=lambda q, x=x, z=z: np.array([0, 0, q[2] - z]) + 1e-3 * np.array([q[0] - x, 0, 0]))
        for k in (0, -1):                                   # tip caps
            ring = F[k]
            cen = ring.mean(axis=0)
            for i in range(len(ring) - 1):
                foil.tri(cen, ring[i], ring[i + 1], outward=lambda q, s=(-1 if k == 0 else 1): np.array([0, s, 0]))
    # propulsion pod on the aft strut, propeller (D = 0.3 m) behind it
    ellipsoid(pod, [-2.40, 0.0, -0.96], [0.30, 0.055, 0.055])
    cylinder(pod, [-2.70, 0, -0.96], [-2.78, 0, -0.96], 0.035, 0.02, n=12)
    for k in range(3):
        a = 2 * math.pi * k / 3
        pts = []
        for r in np.linspace(0.03, 0.15, 7):
            ch = 0.07 * math.sin(math.pi * (r - 0.02) / 0.14) + 0.01
            pitch = math.atan2(0.25, 2 * math.pi * r)       # helical blade, P/D ~ 0.8
            ca, sa = math.cos(a), math.sin(a)
            dy, dz = r * ca, r * sa                          # radial direction
            ty, tz = -sa, ca                                 # tangential direction
            le = np.array([-2.73 + 0.5 * ch * math.sin(pitch), dy + 0.5 * ch * math.cos(pitch) * ty, -0.96 + dz + 0.5 * ch * math.cos(pitch) * tz])
            te = np.array([-2.73 - 0.5 * ch * math.sin(pitch), dy - 0.5 * ch * math.cos(pitch) * ty, -0.96 + dz - 0.5 * ch * math.cos(pitch) * tz])
            pts.append([le, te])
        P = np.array(pts)
        prop.grid(P)
        prop.grid(P[:, ::-1])                                # two-sided blade
    return dict(struts=strut, foils=foil, pod=pod, propeller=prop)


# ------------------------------------------------------------------ pilot
def pilot_meshes():
    body, skin, helmet, seat = Mesh(), Mesh(), Mesh(), Mesh()
    x, z0 = 1.55, sheer_z(1.55) - 0.02
    # seat shell and back rest
    box(seat, [x - 0.30, -0.24, z0], [x + 0.10, 0.24, z0 + 0.10])
    box(seat, [x - 0.36, -0.24, z0], [x - 0.28, 0.24, z0 + 0.45])
    # torso (life vest), legs forward, arms to a tiller/joystick
    ellipsoid(body, [x - 0.15, 0, z0 + 0.42], [0.13, 0.20, 0.27])
    for s in (-1, 1):
        cylinder(body, [x - 0.10, s * 0.10, z0 + 0.16], [x + 0.35, s * 0.10, z0 + 0.20], 0.07, 0.06, n=10)
        cylinder(skin, [x + 0.35, s * 0.10, z0 + 0.20], [x + 0.62, s * 0.10, z0 + 0.04], 0.055, 0.045, n=10)
        cylinder(body, [x - 0.15, s * 0.21, z0 + 0.58], [x + 0.05, s * 0.20, z0 + 0.40], 0.045, n=8)
        cylinder(skin, [x + 0.05, s * 0.20, z0 + 0.40], [x + 0.28, s * 0.12, z0 + 0.42], 0.038, n=8)
    ellipsoid(skin, [x - 0.12, 0, z0 + 0.80], [0.10, 0.085, 0.11])
    ellipsoid(helmet, [x - 0.13, 0, z0 + 0.84], [0.115, 0.10, 0.09])
    cylinder(seat, [x + 0.30, 0, z0 + 0.05], [x + 0.30, 0, z0 + 0.42], 0.015, n=8)    # control column
    return dict(pilot_vest=body, pilot_skin=skin, pilot_helmet=helmet, seat=seat)


# ------------------------------------------------------------------ textures
def write_png(path, img):
    h, w, ch = img.shape
    raw = b"".join(b"\x00" + img[y].tobytes() for y in range(h))

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    ctype = {3: 2, 4: 6}[ch]
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, ctype, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def solar_texture(w=512, h=320, nx=10, ny=6):
    """Monocrystalline cells: dark blue squares with chamfered corners, silver
    busbars and fine fingers, white back-sheet gaps."""
    img = np.zeros((h, w, 3), np.uint8)
    img[:] = (225, 228, 232)                       # back sheet
    cw, chh = w / nx, h / ny
    yy, xx = np.mgrid[0:h, 0:w]
    u = (xx % cw) / cw
    v = (yy % chh) / chh
    gap = 0.03
    inside = (u > gap) & (u < 1 - gap) & (v > gap) & (v < 1 - gap)
    cham = (np.minimum(u, 1 - u) + np.minimum(v, 1 - v)) > 0.11
    cell = inside & cham
    rng = np.random.default_rng(4)
    shade = rng.normal(0, 4, (ny, nx))
    base = np.array([18, 28, 62], float)
    img[cell] = np.clip(base + shade[(yy[cell] / chh).astype(int), (xx[cell] / cw).astype(int)][:, None], 0, 255).astype(np.uint8)
    finger = cell & ((np.abs((v * 24) - np.round(v * 24)) < 0.06))
    img[finger] = (40, 52, 90)
    bus = cell & ((np.abs(u - 0.33) < 0.012) | (np.abs(u - 0.67) < 0.012))
    img[bus] = (170, 175, 185)
    return img


def deck_texture(w=256, h=256):
    """Light grey non-skid deck: fine diamond pattern with noise."""
    yy, xx = np.mgrid[0:h, 0:w]
    d = ((xx + yy) % 16 < 2) | ((xx - yy) % 16 < 2)
    rng = np.random.default_rng(2)
    g = 205 + rng.normal(0, 5, (h, w)) - 18 * d
    return np.clip(np.stack([g, g, g + 3], -1), 0, 255).astype(np.uint8)


def spray_texture(n=64):
    """Soft white disc with alpha falloff, for spray particles."""
    yy, xx = np.mgrid[0:n, 0:n]
    r = np.hypot(xx - n / 2 + 0.5, yy - n / 2 + 0.5) / (n / 2)
    a = np.clip(1 - r, 0, 1) ** 1.8
    img = np.zeros((n, n, 4), np.uint8)
    img[..., :3] = 255
    img[..., 3] = (255 * a).astype(np.uint8)
    return img


def main():
    MESH.mkdir(parents=True, exist_ok=True)
    TEX.mkdir(parents=True, exist_ok=True)
    parts = {}
    for fn in (hull_meshes, solar_meshes, strut_and_foil_meshes, pilot_meshes):
        parts.update(fn())
    # deck texture coordinates: planar projection
    d = parts["deck"]
    d.vt = [(p[0] / 0.6, p[1] / 0.6) for p in d.v]
    d.f = [tuple((i, i) for i, _ in f) for f in d.f]
    total = 0
    for name, m in parts.items():
        total += m.write(MESH / f"{name}.obj")
    write_png(TEX / "solar_cells.png", solar_texture())
    write_png(TEX / "deck_nonskid.png", deck_texture())
    write_png(TEX / "spray.png", spray_texture())
    print(f"wrote {len(parts)} meshes ({total} triangles) and 3 textures to {MODEL}")


if __name__ == "__main__":
    main()
